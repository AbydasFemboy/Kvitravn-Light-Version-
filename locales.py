DEFAULT_LANG = "de"


def _lang(user_id):
    if user_id is None:
        return DEFAULT_LANG
    try:
        return data.load("users", {}).get(str(user_id), {}).get("lang", DEFAULT_LANG) or DEFAULT_LANG
    except Exception:
        return DEFAULT_LANG


def set_lang(user_id, lang):
    users = data.load("users", {})
    users[str(user_id)] = {**users.get(str(user_id), {}), "lang": lang}
    data.save("users", users)


def t(user_id, key, **kwargs):
    table = TEXTS.get(_lang(user_id), TEXTS[DEFAULT_LANG])
    text = table.get(key, TEXTS[DEFAULT_LANG].get(key, key))
    if not kwargs:
        return text
    try:
        return text.format(**kwargs)
    except Exception:
        return text
